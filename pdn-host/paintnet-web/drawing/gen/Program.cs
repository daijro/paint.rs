// Writes the public API of a System.Drawing.Common build as C# stubs: every public and protected type and member,
// with the same names and signatures, each body throwing Unsupported. Only the API is read (by reflection over the
// assembly's metadata); no implementation is copied. Members listed in implemented.txt are left out, for the
// hand-written partial classes beside the stubs to define.
//
//   dotnet run --project gen -- <System.Drawing.Common.dll> <implemented.txt> <out.cs>
//   dotnet run --project gen -- <System.Drawing.Common.dll> --missing <our build>   (lists what the build lacks)
//
// implemented.txt holds one key per line: a type's full name (the whole type is hand-written), "Type::Name(*)" (every
// overload of a name), or a member key as --keys prints it, e.g. "System.Drawing.Bitmap::.ctor(System.Int32,System.Int32)" or "System.Drawing.Image::P:Width".
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;

const BindingFlags Declared = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
var asm = Assembly.LoadFrom(args[0]);
if (args[1] == "--keys")   // print the member keys of type args[2], to copy into implemented.txt
{
    var kt = asm.GetType(args[2], true)!;
    foreach (var c in kt.GetConstructors(Declared).Where(Visible)) Console.WriteLine($"{Full(kt)}::{Sig(".ctor", c)}");
    foreach (var p in kt.GetProperties(Declared)) Console.WriteLine($"{Full(kt)}::P:{p.Name}" + (p.GetIndexParameters() is { Length: > 0 } ix ? "[" + string.Join(",", ix.Select(i => Full(i.ParameterType))) + "]" : ""));
    foreach (var e in kt.GetEvents(Declared)) Console.WriteLine($"{Full(kt)}::E:{e.Name}");
    foreach (var m in kt.GetMethods(Declared).Where(m => Visible(m) && !m.IsSpecialName || m.Name.StartsWith("op_"))) Console.WriteLine($"{Full(kt)}::{Sig(m.Name, m)}");
    foreach (var i in kt.GetInterfaces()) foreach (var im in i.GetMethods()) Console.WriteLine($"{Full(kt)}::{Full(i)}.{im.Name}");
    return;
}
if (args[1] == "--missing")   // print every public member of args[0] that the build args[2] lacks
{
    var built = new System.Runtime.Loader.AssemblyLoadContext("built").LoadFromAssemblyPath(Path.GetFullPath(args[2]));
    var have = Keys(built).ToHashSet();
    var missing = Keys(asm).Where(k => !have.Contains(k)).ToList();
    missing.ForEach(Console.WriteLine);
    Console.Error.WriteLine($"{missing.Count} missing");
    Environment.ExitCode = missing.Count == 0 ? 0 : 1;
    return;
}
var skip = File.Exists(args[1]) ? File.ReadAllLines(args[1]).Select(l => l.Trim()).Where(l => l.Length > 0 && !l.StartsWith('#')).ToHashSet() : [];
var outPath = args[2];

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated> by drawing/gen from System.Drawing.Common's public API: signatures only, every body a stub.");
sb.AppendLine("// Regenerate rather than edit; implement a member in a partial class and list it in implemented.txt.");
sb.AppendLine("#nullable disable");
sb.AppendLine("#pragma warning disable CS0067, CS0108, CS0114, CS0618, CS0659, CS0660, CS0661, CS1591, CS8618, SYSLIB0003, SYSLIB0050, SYSLIB0051");
int types = 0, members = 0, skipped = 0;

foreach (var ns in asm.GetExportedTypes().Where(t => !t.IsNested).GroupBy(t => t.Namespace).OrderBy(g => g.Key))
{
    sb.AppendLine($"namespace {ns.Key}");
    sb.AppendLine("{");
    foreach (var t in ns.OrderBy(t => t.Name)) EmitType(t, 1);
    sb.AppendLine("}");
}
File.WriteAllText(outPath, sb.ToString());
Console.WriteLine($"{types} types, {members} members written; {skipped} left to the hand-written code");

void EmitType(Type t, int depth)
{
    if (skip.Contains(Full(t))) { skipped++; return; }
    types++;
    string ind = new(' ', depth * 4);
    string vis = t.IsNestedFamily ? "protected" : "public";
    if (t.IsEnum)
    {
        if (t.IsDefined(typeof(FlagsAttribute))) sb.AppendLine($"{ind}[global::System.Flags]");
        sb.AppendLine($"{ind}{vis} enum {t.Name} : {N(Enum.GetUnderlyingType(t))}");
        sb.AppendLine($"{ind}{{");
        foreach (var f in t.GetFields(BindingFlags.Public | BindingFlags.Static))
            sb.AppendLine($"{ind}    {f.Name} = {Literal(Convert.ChangeType(f.GetRawConstantValue(), Enum.GetUnderlyingType(t)))},");
        sb.AppendLine($"{ind}}}");
        return;
    }
    if (typeof(Delegate).IsAssignableFrom(t) && t != typeof(Delegate) && t != typeof(MulticastDelegate))
    {
        var invoke = t.GetMethod("Invoke")!;
        sb.AppendLine($"{ind}{vis} delegate {N(invoke.ReturnType)} {Name(t)}({Params(invoke)});");
        return;
    }
    string kind = t.IsInterface ? "interface" : t.IsValueType ? "struct" : "class";
    string mods = t.IsInterface || t.IsValueType ? "" : t.IsAbstract && t.IsSealed ? "static " : t.IsAbstract ? "abstract " : t.IsSealed ? "sealed " : "";
    var bases = new List<string>();
    if (!t.IsInterface && !t.IsValueType && t.BaseType != typeof(object) && t.BaseType != null) bases.Add(N(t.BaseType));
    var inherited = t.BaseType?.GetInterfaces() ?? [];
    foreach (var i in t.GetInterfaces().Where(i => i.IsPublic || i.IsNestedPublic))
        if (t.IsInterface ? !t.GetInterfaces().Any(o => o != i && o.GetInterfaces().Contains(i)) : !inherited.Contains(i)) bases.Add(N(i));
    sb.AppendLine($"{ind}{vis} {mods}unsafe partial {kind} {Name(t)}{(bases.Count > 0 ? " : " + string.Join(", ", bases) : "")}");
    sb.AppendLine($"{ind}{{");
    string ind2 = ind + "    ";
    bool isStatic = t.IsAbstract && t.IsSealed;

    foreach (var f in t.GetFields(Declared).Where(f => f.IsPublic || f.IsFamily || f.IsFamilyOrAssembly))
    {
        if (Skip(t, "F:" + f.Name)) continue;
        members++;
        string fv = f.IsFamily ? "protected" : "public";
        if (f.IsLiteral) sb.AppendLine($"{ind2}{fv} const {N(f.FieldType)} {f.Name} = {Literal(f.GetRawConstantValue())};");
        else sb.AppendLine($"{ind2}{fv} {(f.IsStatic ? "static " : "")}{(f.IsInitOnly ? "readonly " : "")}{N(f.FieldType)} {f.Name};");
    }

    var ctors = t.GetConstructors(Declared).Where(Visible).ToList();
    foreach (var c in ctors)
    {
        if (t.IsValueType && c.GetParameters().Length == 0) continue;
        if (Skip(t, Sig(".ctor", c))) continue;
        members++;
        sb.AppendLine($"{ind2}{Vis(c)} {Name(t, bare: true)}({Params(c)}){BaseCall(t)} => throw global::System.Drawing.Unsupported.Member(\"{Full(t)}..ctor\");");
    }
    // Derived stubs need a constructor to chain to; a type whose own are not public gets a hidden one.
    if (!t.IsInterface && !t.IsValueType && !isStatic && !ctors.Any(c => c.GetParameters().Length == 0) && !skip.Contains($"{Full(t)}::.ctor()"))
        sb.AppendLine($"{ind2}private protected {Name(t, bare: true)}(){BaseCall(t)} {{ }}");

    var accessors = new HashSet<MethodInfo>();
    foreach (var p in t.GetProperties(Declared))
    {
        var get = p.GetMethod is { } g && Visible(g) ? g : null;
        var set = p.SetMethod is { } s && Visible(s) ? s : null;
        if (p.GetMethod != null) accessors.Add(p.GetMethod);
        if (p.SetMethod != null) accessors.Add(p.SetMethod);
        if (get == null && set == null) continue;
        var idx = p.GetIndexParameters();
        if (Skip(t, "P:" + p.Name + (idx.Length > 0 ? "[" + string.Join(",", idx.Select(i => Full(i.ParameterType))) + "]" : ""))) continue;
        members++;
        var lead = get ?? set!;
        string head = $"{Vis(lead)} {Mods(lead, t)}{N(p.PropertyType)} {(idx.Length > 0 ? "this[" + string.Join(", ", idx.Select(Param)) + "]" : p.Name)}";
        if (t.IsInterface) { sb.AppendLine($"{ind2}{N(p.PropertyType)} {(idx.Length > 0 ? "this[" + string.Join(", ", idx.Select(Param)) + "]" : p.Name)} {{ {(get != null ? "get; " : "")}{(set != null ? "set; " : "")}}}"); continue; }
        string Acc(MethodInfo m, string kw) => (Vis(m) != Vis(lead) ? Vis(m) + " " : "") + kw + (lead.IsAbstract ? ";" : $" => throw global::System.Drawing.Unsupported.Member(\"{Full(t)}.{p.Name}\");");
        sb.AppendLine($"{ind2}{head} {{ {(get != null ? Acc(get, "get") + " " : "")}{(set != null ? Acc(set, "set") + " " : "")}}}");
    }
    foreach (var e in t.GetEvents(Declared))
    {
        if (e.AddMethod is not { } add || !Visible(add)) continue;
        accessors.Add(add);
        if (e.RemoveMethod != null) accessors.Add(e.RemoveMethod);
        if (Skip(t, "E:" + e.Name)) continue;
        members++;
        if (t.IsInterface) { sb.AppendLine($"{ind2}event {N(e.EventHandlerType!)} {e.Name};"); continue; }
        sb.AppendLine($"{ind2}{Vis(add)} {Mods(add, t)}event {N(e.EventHandlerType!)} {e.Name}" + (add.IsAbstract ? ";" : " { add { } remove { } }"));
    }
    foreach (var m in t.GetMethods(Declared).Where(m => Visible(m) && !accessors.Contains(m) && m.Name != "Finalize"))
    {
        if (Skip(t, Sig(m.Name, m))) continue;
        members++;
        string gen = m.IsGenericMethodDefinition ? "<" + string.Join(", ", m.GetGenericArguments().Select(a => a.Name)) + ">" : "";
        if (t.IsInterface) { sb.AppendLine($"{ind2}{N(m.ReturnType)} {m.Name}{gen}({Params(m)});"); continue; }
        string body = m.IsAbstract ? ";" : $" => throw global::System.Drawing.Unsupported.Member(\"{Full(t)}.{m.Name}\");";
        if (m.Name is "op_Implicit" or "op_Explicit")
            sb.AppendLine($"{ind2}public static {(m.Name == "op_Implicit" ? "implicit" : "explicit")} operator {N(m.ReturnType)}({Params(m)}){body}");
        else if (m.IsSpecialName && m.Name.StartsWith("op_"))
            sb.AppendLine($"{ind2}public static {N(m.ReturnType)} operator {Operator(m.Name)}({Params(m)}){body}");
        else
            sb.AppendLine($"{ind2}{Vis(m)} {Mods(m, t)}{N(m.ReturnType)} {m.Name}{gen}({Params(m)}){body}");
    }
    // Interface members the type implements privately (explicitly) in the original.
    if (!t.IsInterface)
        foreach (var i in t.GetInterfaces().Where(i => i.IsPublic && !inherited.Contains(i)))
        {
            var map = t.GetInterfaceMap(i);
            for (int k = 0; k < map.TargetMethods.Length; k++)
            {
                var target = map.TargetMethods[k];
                if (target == null || Visible(target) || target.DeclaringType != t) continue;
                var im = map.InterfaceMethods[k];
                if (skip.Contains($"{Full(t)}::{Full(i)}.{im.Name}")) { skipped++; continue; }
                if (im.IsSpecialName && (im.Name.StartsWith("get_") || im.Name.StartsWith("set_")))
                {
                    if (im.Name.StartsWith("set_") && i.GetProperty(im.Name[4..])?.GetMethod != null) continue;   // emitted with its getter
                    var prop = i.GetProperty(im.Name[4..])!;
                    sb.AppendLine($"{ind2}{N(prop.PropertyType)} {N(i)}.{prop.Name} {{ {(prop.GetMethod != null ? "get => throw null; " : "")}{(prop.SetMethod != null ? "set => throw null; " : "")}}}");
                }
                else if (!im.IsSpecialName)
                    sb.AppendLine($"{ind2}{N(im.ReturnType)} {N(i)}.{im.Name}({Params(im)}) => throw global::System.Drawing.Unsupported.Member(\"{Full(t)}.{im.Name}\");");
            }
        }
    foreach (var nested in t.GetNestedTypes(BindingFlags.Public | BindingFlags.NonPublic).Where(n => (n.IsNestedPublic || n.IsNestedFamily) && !n.Name.Contains('<')).OrderBy(n => n.Name))
        EmitType(nested, depth + 1);
    sb.AppendLine($"{ind}}}");
}

// Every public type and visible member of an assembly, as keys.
static IEnumerable<string> Keys(Assembly a)
{
    foreach (var t in a.GetTypes().Where(t => (t.IsPublic || t.IsNestedPublic || t.IsNestedFamily) && !t.Name.Contains('<')))
    {
        yield return Full(t);
        foreach (var c in t.GetConstructors(Declared).Where(Visible)) yield return $"{Full(t)}::{Sig(".ctor", c)}";
        foreach (var p in t.GetProperties(Declared).Where(p => p.GetAccessors(true).Any(Visible))) yield return $"{Full(t)}::P:{p.Name}";
        foreach (var e in t.GetEvents(Declared).Where(e => Visible(e.AddMethod))) yield return $"{Full(t)}::E:{e.Name}";
        foreach (var f in t.GetFields(Declared).Where(f => f.IsPublic || f.IsFamily || f.IsFamilyOrAssembly)) yield return $"{Full(t)}::F:{f.Name}";
        foreach (var m in t.GetMethods(Declared).Where(m => Visible(m) && m.Name != "Finalize" && (!m.IsSpecialName || m.Name.StartsWith("op_")))) yield return $"{Full(t)}::{Sig(m.Name, m)}";
    }
}

// A member's own key, or "Type::Name(*)" for every overload of a name.
bool Skip(Type t, string member)
{
    int paren = member.IndexOf('(');
    if (!skip.Contains($"{Full(t)}::{member}") && !(paren > 0 && skip.Contains($"{Full(t)}::{member[..paren]}(*)"))) return false;
    skipped++;
    return true;
}

static bool Visible(MethodBase m) => m.IsPublic || m.IsFamily || m.IsFamilyOrAssembly;
static string Vis(MethodBase m) => m.IsPublic ? "public" : m.IsFamilyOrAssembly ? "protected internal" : "protected";

static string Mods(MethodInfo m, Type t)
{
    if (t.IsAbstract && t.IsSealed || m.IsStatic) return "static ";
    if (m.IsAbstract) return t.IsInterface ? "" : m.GetBaseDefinition() != m ? "abstract override " : "abstract ";
    if (!m.IsVirtual) return "";
    bool overrides = m.GetBaseDefinition() != m;
    if (m.IsFinal) return overrides ? "sealed override " : "";
    return overrides ? "override " : "virtual ";
}

// Our own bases have a hidden parameterless constructor; another assembly's may need arguments (EnumConverter).
static string BaseCall(Type t)
{
    if (t.BaseType is not { } b || t.IsValueType) return "";
    if (b.Assembly == t.Assembly) return " : base()";
    var ctors = b.GetConstructors(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance).Where(Visible).ToList();
    if (ctors.Count == 0 || ctors.Any(c => c.GetParameters().Length == 0)) return "";
    return " : base(" + string.Join(", ", ctors[0].GetParameters().Select(p => $"default({N(p.ParameterType)})")) + ")";
}

static string Sig(string name, MethodBase m) => $"{name}({string.Join(",", m.GetParameters().Select(p => Full(p.ParameterType)))})";

// A type's name with its generic arguments spelled the same way, never assembly-qualified (our build has its own identity).
static string Full(Type t)
{
    if (t.IsByRef) return Full(t.GetElementType()!) + "&";
    if (t.IsPointer) return Full(t.GetElementType()!) + "*";
    if (t.IsArray) return Full(t.GetElementType()!) + "[" + new string(',', t.GetArrayRank() - 1) + "]";
    if (t.IsGenericType && !t.IsGenericTypeDefinition) return $"{Full(t.GetGenericTypeDefinition())}[{string.Join(",", t.GetGenericArguments().Select(Full))}]";
    return (t.FullName ?? t.Name).Replace('+', '.');
}

static string Name(Type t, bool bare = false)
{
    string n = t.Name.Contains('`') ? t.Name[..t.Name.IndexOf('`')] : t.Name;
    if (bare || !t.IsGenericTypeDefinition) return n;
    return n + "<" + string.Join(", ", t.GetGenericArguments().Select(a => a.Name)) + ">";
}

static string Params(MethodBase m) => string.Join(", ", m.GetParameters().Select(Param));

static string Param(ParameterInfo p)
{
    var t = p.ParameterType;
    string mod = t.IsByRef ? p.IsOut ? "out " : p.IsIn ? "in " : "ref " : p.IsDefined(typeof(ParamArrayAttribute)) ? "params " : "";
    string s = $"{mod}{N(t.IsByRef ? t.GetElementType()! : t)} @{p.Name}";
    if (p.HasDefaultValue && !t.IsByRef) s += " = " + (p.DefaultValue == null ? "default" : Literal(p.DefaultValue, t));
    return s;
}

static string Literal(object v, Type? t = null)
{
    if (t != null && t.IsEnum) return $"({N(t)}){Literal(Convert.ChangeType(v, Enum.GetUnderlyingType(t)))}";
    return v switch
    {
        null => "null",
        bool b => b ? "true" : "false",
        string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
        char c => $"(char){(int)c}",
        float f => float.IsNaN(f) ? "float.NaN" : float.IsPositiveInfinity(f) ? "float.PositiveInfinity" : float.IsNegativeInfinity(f) ? "float.NegativeInfinity" : f.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f",
        double d => double.IsNaN(d) ? "double.NaN" : d.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d",
        long l => l == long.MinValue ? "long.MinValue" : l + "L",
        ulong u => u + "UL",
        uint u => u + "U",
        int i => i == int.MinValue ? "int.MinValue" : i.ToString(),
        short or ushort or byte or sbyte => $"({N(v.GetType())}){v}",
        decimal m => m.ToString(System.Globalization.CultureInfo.InvariantCulture) + "m",
        _ => v.ToString()!,
    };
}

static string N(Type t)
{
    if (t.IsByRef) return N(t.GetElementType()!);
    if (t.IsPointer) return N(t.GetElementType()!) + "*";
    if (t.IsArray) return N(t.GetElementType()!) + "[" + new string(',', t.GetArrayRank() - 1) + "]";
    if (t.IsGenericParameter) return t.Name;
    string? kw = Type.GetTypeCode(t) switch
    {
        TypeCode.Boolean => "bool", TypeCode.Byte => "byte", TypeCode.SByte => "sbyte", TypeCode.Char => "char",
        TypeCode.Int16 => "short", TypeCode.UInt16 => "ushort", TypeCode.Int32 => "int", TypeCode.UInt32 => "uint",
        TypeCode.Int64 => "long", TypeCode.UInt64 => "ulong", TypeCode.Single => "float", TypeCode.Double => "double",
        TypeCode.Decimal => "decimal", TypeCode.String => "string", _ => null,
    };
    if (kw != null && !t.IsEnum) return kw;
    if (t == typeof(void)) return "void";
    if (t == typeof(object)) return "object";
    if (t.IsGenericType)
    {
        var def = t.GetGenericTypeDefinition();
        string name = def.FullName!.Replace('+', '.');
        name = name[..name.IndexOf('`')];
        return "global::" + name + "<" + string.Join(", ", t.GetGenericArguments().Select(N)) + ">";
    }
    return "global::" + t.FullName!.Replace('+', '.');
}

static string Operator(string name) => name switch
{
    "op_Equality" => "==", "op_Inequality" => "!=", "op_Addition" => "+", "op_Subtraction" => "-", "op_Multiply" => "*",
    "op_Division" => "/", "op_UnaryNegation" => "-", "op_UnaryPlus" => "+", "op_LessThan" => "<", "op_GreaterThan" => ">",
    "op_LessThanOrEqual" => "<=", "op_GreaterThanOrEqual" => ">=", _ => throw new NotSupportedException(name),
};
